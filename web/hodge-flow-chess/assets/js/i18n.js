  const listeners = [];

  const API = {
    get lang() { return lang; },
    t: function (key, vars) {
      let s;
      if (lang === 'en') s = (EN[key] !== undefined ? EN[key] : (RU[key] !== undefined ? RU[key] : key));
      else s = (RU[key] !== undefined ? RU[key] : (EN[key] !== undefined ? EN[key] : key));
      if (vars) {
        Object.keys(vars).forEach(function (k) {
          s = s.split('{' + k + '}').join(String(vars[k]));
        });
      }
      return s;
    },
    setLang: function (l) {
      if (l !== 'ru' && l !== 'en') return;
      lang = l;
      try { localStorage.setItem('hf_lang', l); } catch (e) { /* ignore */ }
      API.apply(); // apply static texts first, then listeners re-render dynamic parts
      listeners.forEach(function (fn) { try { fn(l); } catch (e2) { /* ignore */ } });
    },
    onChange: function (fn) { listeners.push(fn); },
    apply: function () {
      document.documentElement.setAttribute('lang', lang);
      const nodes = document.querySelectorAll('[data-i18n]');
      for (let i = 0; i < nodes.length; i++) {
        nodes[i].textContent = API.t(nodes[i].getAttribute('data-i18n'));
      }
      const tips = document.querySelectorAll('[data-i18n-title]');
      for (let i = 0; i < tips.length; i++) {
        tips[i].setAttribute('title', API.t(tips[i].getAttribute('data-i18n-title')));
        tips[i].setAttribute('aria-label', API.t(tips[i].getAttribute('data-i18n-title')));
      }
      const phs = document.querySelectorAll('[data-i18n-ph]');
      for (let i = 0; i < phs.length; i++) {
        phs[i].setAttribute('placeholder', API.t(phs[i].getAttribute('data-i18n-ph')));
      }
    },
  };

  window.HFI18n = API;
