/* chess-oracle · tb.js
   Frozen DTM tablebase loader and probe API.

   Data source: assets/data/tables.js (generated by scripts/export_web_tables.py
   from the frozen certificates results/dtm_{krk,kqk,knk,kpk}.json.gz).
   Packing: state = wk | wp<<7 | bk<<14 | stm<<21 (bit 21 = Black to move),
   byte value 0..63 = DTM in plies, 200 = drawn / illegal.

   Endgames:
     krk / kqk — the original certificates (T11);
     knk       — the negative control: won = mates = 0, a knight mate does
                 not exist; the integrity gate re-proves it on every load;
     kpk       — retrograde with the promotion boundary: the child of a
                 promotion ply is a KQK state, read from the frozen KQK
                 certificate (queen promotion is DTM-sufficient).

   On load the app verifies the payload against the FROZEN constants — the
   same numbers that certify the retrograde build. Any mismatch raises the
   red banner: the oracle refuses to pretend. */

(function (global) {
  'use strict';

  var C = global.ChessOracle.chess;

  var FROZEN = {
    krk: {
      label: 'K+R vs K',
      piece: 'R',
      pieceCode: C.WR,
      stats: { states: 399112, edges: 4447032, won: 376868,
               mates: 216, max_plies: 32, max_moves: 16 },
      frozenE1: { save_rate: 0.8244, optimal_rate: 0.303,
                  mean_delta_plies: 2.9452 },
      frozenE3: { log10_tree: 5.70, max_tree_nodes: '500900' }
    },
    kqk: {
      label: 'K+Q vs K',
      piece: 'Q',
      pieceCode: C.WQ,
      stats: { states: 368452, edges: 4869496, won: 345404,
               mates: 364, max_plies: 20, max_moves: 10 },
      frozenE1: { save_rate: 0.9562, optimal_rate: 0.2648,
                  mean_delta_plies: 2.3301 },
      frozenE3: { log10_tree: 3.559, max_tree_nodes: '3626' }
    },
    knk: {
      label: 'K+N vs K',
      piece: 'N',
      pieceCode: C.WN,
      stats: { states: 429440, edges: 3521256, won: 0,
               mates: 0, max_plies: 0, max_moves: 0 },
      frozenE1: null,                       // no won states: E1 not applicable
      frozenE3: null                        // the minimal tree is empty (T15)
    },
    kpk: {
      label: 'K+P vs K',
      piece: 'P',
      pieceCode: C.WP,
      stats: { states: 331352, edges: 2125630, won: 222558,
               mates: 0, max_plies: 56, max_moves: 28 },
      frozenE1: null,                       // live measurement only (no
      frozenE3: null                        // Python twin for KPK yet)
    }
  };

  var SIZE = 1 << 22;
  var cache = {};                           // kind -> loaded tablebase

  function packState(wk, wp, bk, stm) {
    return wk | (wp << 7) | (bk << 14) | (stm << 21);
  }

  function unpackState(s) {
    return { wk: s & 127, wp: (s >> 7) & 127, bk: (s >> 14) & 127,
             stm: (s >> 21) & 1 };         // stm: 0 white, 1 black
  }

  function stateOfPosition(pos) {
    var wk = pos.kingSquare(1), bk = pos.kingSquare(-1),
        wp = pos.strongSquare();
    if (wk < 0 || bk < 0 || wp < 0) return null;
    return packState(wk, wp, bk, pos.side === -1 ? 1 : 0);
  }

  function gunzip(bytes) {
    if (typeof DecompressionStream === 'undefined') {
      return Promise.reject(new Error(
        'DecompressionStream is not supported by this browser'));
    }
    var stream = new Blob([bytes]).stream().pipeThrough(
      new DecompressionStream('gzip'));
    return new Response(stream).arrayBuffer()
      .then(function (buf) { return new Uint8Array(buf); });
  }

  function loadTablebase(kind) {
    if (cache[kind]) return Promise.resolve(cache[kind]);
    var spec = FROZEN[kind];
    var payload = (global.CHESS_ORACLE_DATA || {})[kind];
    if (!payload) {
      return Promise.reject(new Error(
        'tables.js payload missing for ' + kind));
    }
    // ── integrity gate against the frozen certificate ──────────────────
    var checks = [];
    Object.keys(spec.stats).forEach(function (k) {
      checks.push({ name: 'stats.' + k, expected: spec.stats[k],
                    actual: payload.stats[k],
                    ok: payload.stats[k] === spec.stats[k] });
    });
    checks.push({ name: 'bellman_verified', expected: true,
                  actual: payload.bellman_verified === true,
                  ok: payload.bellman_verified === true });
    return gunzip(Uint8Array.from(atob(payload.blob),
      function (ch) { return ch.charCodeAt(0); }))
      .then(function (dtm) {
        checks.push({ name: 'blob_bytes', expected: SIZE,
                      actual: dtm.length, ok: dtm.length === SIZE });
        var wonCount = 0, mates = 0;
        for (var s = 0; s < SIZE; s++) {
          var v = dtm[s];
          if (v < 200) { wonCount++; if (v === 0) mates++; }
        }
        checks.push({ name: 'recount.won', expected: spec.stats.won,
                      actual: wonCount, ok: wonCount === spec.stats.won });
        checks.push({ name: 'recount.mates', expected: spec.stats.mates,
                      actual: mates, ok: mates === spec.stats.mates });
        var result = {
          kind: kind,
          spec: spec,
          blob: dtm,
          checks: checks,
          allOk: checks.every(function (c) { return c.ok; }),
          probe: function (state) {
            if (state == null || state < 0 || state >= SIZE) {
              return { raw: 200, won: false, mate: false, drawn: true,
                       plies: null };
            }
            var v2 = dtm[state];
            return { raw: v2, won: v2 < 200, mate: v2 === 0,
                     drawn: v2 === 200, plies: v2 < 200 ? v2 : null };
          }
        };
        cache[kind] = result;
        return result;
      });
  }

  function getLoaded(kind) {
    return cache[kind] || null;
  }

  function preloadAll() {
    return Promise.all(Object.keys(FROZEN).map(function (k) {
      return loadTablebase(k);
    }));
  }

  /* Probe the position that results from `m`. Handles the KPK promotion
     boundary: the promoted child is a KQK state and is read from the
     frozen KQK certificate. Value semantics match internal children: the
     returned plies v EXCLUDES the move ply itself (parent move value is
     v + 1 plies). Returns null when the strong piece was captured
     (K vs K: outside every packed space, drawn) or when the boundary
     table is not yet loaded. */
  function probeAfterMove(tb, pos, m) {
    var undo = pos.make(m);
    var res;
    if (tb.kind === 'kpk' && undo.promo) {
      var kqk = cache.kqk;
      res = kqk ? kqk.probe(packState(pos.kingSquare(1), m.t,
                                      pos.kingSquare(-1), 1))
                : null;
    } else {
      var st = stateOfPosition(pos);
      res = st === null ? null : tb.probe(st);
    }
    pos.unmake(undo);
    return res;
  }

  /* Optimal moves for the side to move, by table semantics:
     - White (stm 0) won with d plies: every move to a child with d-1
       (a promotion child is valued through the KQK certificate);
     - Black (stm 1) won-against with d plies: maximize the child value
       (a drawn child = escape, value 200 = best possible defence);
     - a drawn side: any legal move keeps the draw (audited separately). */
  function optimalMoves(tb, pos, state) {
    var info = tb.probe(state);
    var moves = pos.legalMoves();
    var out = [], i, child;
    var isWhite = pos.side === 1;
    if (info.won && !info.mate) {
      var d = info.plies;
      for (i = 0; i < moves.length; i++) {
        child = probeAfterMove(tb, pos, moves[i]);
        if (isWhite) {
          if (child != null && child.won && child.plies === d - 1) {
            out.push(moves[i]);
          }
        } else if (child == null || !child.won) {
          out.push(moves[i]);               // escape to a draw (K vs K too)
        }
      }
      if (out.length === 0 && !isWhite) {
        // no escape: maximize resistance (longest remaining DTM)
        var best = -1;
        for (i = 0; i < moves.length; i++) {
          child = probeAfterMove(tb, pos, moves[i]);
          var pv = child && child.won ? child.plies : -1;
          if (pv > best) { best = pv; out = [moves[i]]; }
          else if (child && child.won && pv === best) out.push(moves[i]);
        }
      }
      return out;
    }
    return moves.slice();      // drawn side: everything is equivalent
  }

  global.ChessOracle = global.ChessOracle || {};
  global.ChessOracle.tb = {
    FROZEN: FROZEN, SIZE: SIZE,
    packState: packState, unpackState: unpackState,
    stateOfPosition: stateOfPosition,
    loadTablebase: loadTablebase, preloadAll: preloadAll,
    getLoaded: getLoaded, probeAfterMove: probeAfterMove,
    optimalMoves: optimalMoves
  };
})(window);
